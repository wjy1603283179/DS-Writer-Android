/**
 * Optional local signing.
 *
 * A public release must not be signed with anyone's private release key, so signing is used only
 * when it is both configured and explicitly allowed. Pass `-PdsWriterSigning=off` to build an
 * unsigned release even on a machine that has signing material present.
 */
val releaseSigningPropertiesFile = file(
    "${System.getProperty("user.home")}/.gradle/dswriter-release/signing.properties",
)
val releaseSigningProperties = Properties().apply {
    if (releaseSigningPropertiesFile.isFile) {
        releaseSigningPropertiesFile.inputStream().use(::load)
    }
}
val dsWriterSigningDisabled =
    (project.findProperty("dsWriterSigning") as String?)?.equals("off", ignoreCase = true) == true
val dsWriterKeystoreFile = releaseSigningProperties.getProperty("storeFile")
    ?.let { file(it) }
    ?.takeIf { it.isFile }
val useReleaseSigning =
    !dsWriterSigningDisabled && releaseSigningPropertiesFile.isFile && dsWriterKeystoreFile != null

android {
    namespace = "app.dswriter"
    compileSdk = 35
    buildToolsVersion = "35.0.0"

    defaultConfig {
        applicationId = "app.dswriter"
        minSdk = 31
        targetSdk = 35
        versionCode = 1
        versionName = "1.0.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables.useSupportLibrary = true
    }

    signingConfigs {
        create("release") {
            if (useReleaseSigning) {
                storeFile = dsWriterKeystoreFile
                storePassword = releaseSigningProperties.getProperty("storePassword")
                keyAlias = releaseSigningProperties.getProperty("keyAlias")
                keyPassword = releaseSigningProperties.getProperty("keyPassword")
                storeType = releaseSigningProperties.getProperty("storeType", "PKCS12")
            }
        }
    }

    buildTypes {
        release {
            if (useReleaseSigning) {
                signingConfig = signingConfigs.getByName("release")
            }
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }

    sourceSets["androidTest"].assets.srcDir("$projectDir/schemas")
}

